"""Valida o primeiro checkout da Casa Nala a partir da entrada pública."""
import os
from pathlib import Path
from playwright.sync_api import expect, sync_playwright

url = Path(os.getenv("ORDERX_MAQUETA", "public/maqueta/index.html")).resolve().as_uri()
with sync_playwright() as pw:
    browser = pw.chromium.launch(executable_path=os.getenv("CHROMIUM_PATH"))
    for width in [390, 820, 1440]:
        context = browser.new_context(viewport={"width": width, "height": 900})
        page = context.new_page()
        page.goto(url)
        page.get_by_role("link", name="Entrar", exact=True).click()
        page.get_by_text("Casa Nala").click()
        page.get_by_text("Começar", exact=True).click()
        page.get_by_label("Nome do produto").fill("Cesto de palha")
        page.get_by_label("Preço por unidade").fill("249.50")
        page.get_by_text("Guardar produto").click()
        page.get_by_label("Entrega fixa").fill("75")
        page.get_by_label("Quantidade máxima").fill("3")
        page.get_by_text("Pré-visualizar").click()
        expect(page.get_by_text("Prévia do comprador")).to_be_visible()
        page.get_by_text("Editar configuração").click()
        expect(page.get_by_label("Entrega fixa")).to_have_value("75")
        page.get_by_text("Pré-visualizar").click()
        page.get_by_text("Publicar link").click()
        published = page.get_by_label("Link publicado").input_value()
        page.reload()
        expect(page.get_by_label("Link publicado")).to_have_value(published)
        buyer = page.context.new_page()
        buyer.goto(published)
        expect(buyer.get_by_label("Quantidade")).to_be_visible()
        page.goto(url+"#/loja/nala/encomendas")
        buyer.get_by_label("Quantidade").select_option("3")
        expect(buyer.locator("output")).to_have_text("823,50 MT")
        buyer.get_by_label("Nome fictício").fill("Cliente Nala")
        buyer.get_by_label("Telefone fictício").fill("841234567")
        buyer.get_by_label("Morada fictícia").fill("Maputo")
        buyer.get_by_role("button").click()
        expect(buyer.get_by_text("••• 567")).to_be_visible()
        page.get_by_role("link", name="NALA-").click()
        expect(page.get_by_text("Cesto de palha")).to_be_visible()
        page.get_by_text("Confirmar encomenda").click()
        expect(page.get_by_text("Confirmada",exact=True)).to_be_visible()
        page.goto(url+"#/loja/amora/encomendas")
        expect(page.get_by_text("Cliente Nala",exact=False)).to_have_count(0)
        page.context.close()
        print("PASS Casa Nala",width)
